namespace Lumis;

/// <summary>Mouse buttons that can be polled through <see cref="InputState"/>.</summary>
public enum MouseButton
{
    /// <summary>The left mouse button.</summary>
    Left = 0,
    /// <summary>The right mouse button.</summary>
    Right = 1,
    /// <summary>The middle button, usually the scroll wheel.</summary>
    Middle = 2,
    /// <summary>The first side button.</summary>
    Side = 3,
    /// <summary>The second side button.</summary>
    Extra = 4,
    /// <summary>The forward navigation button.</summary>
    Forward = 5,
    /// <summary>The back navigation button.</summary>
    Back = 6
}
